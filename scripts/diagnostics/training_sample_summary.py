"""Writes results/training_sample_v1.md: the numbers of the training-sample study quoted in the paper (validation
only; Canto-L trained on HNL and on ttbar + HNL with one seed each). Inputs: results/training_sample_val_{mwslmerge,
mwslayermerge}.csv (hnl.eval.training_sample_board), results/strong_baselines_v3_val_differences.csv (three-seed
uncertainties), RUN/edge_tpr_estar.csv of the three Canto-L runs, results/oblique_val_{ref,ii,iii}_v1_particles.csv,
results/diagnostics/valmon_split.txt and ttbar_cmp_6717924.txt (same-setting comparison), and
results/training_sample_paired_v1.csv (hnl.eval.training_sample_paired: the uncertainties of the differences, paired over
the events as Eq. (sigma) of the paper states; until 2026-10-08 this file added the two models' sigmas in quadrature).

    python3 scripts/diagnostics/training_sample_summary.py
"""
import os

import numpy as np
import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(REPO, "results")
RUNS = "/ceph/submit/data/user/j/jinboz1/hnl_lrt/runs"
CANTO = {"ttbar": f"{RUNS}/stage1_final_learned/l1tl/armi_s0", "HNL": f"{RUNS}/stage1_final_learned_ts/l1tl/armii_s0",
         "ttbar+HNL": f"{RUNS}/stage1_final_learned_ts/l1tl/armiii_s0"}
MODELS = ["acorn (ttbar)", "acorn (ttbar+HNL)", "acorn (HNL)", "Canto-L (ttbar)", "Canto-L (ttbar+HNL)", "Canto-L (HNL)"]
SB_LABEL = {"mwslmerge": {"acorn (ttbar)": "acorn (ttbar) + MWS-layer + learned merging (Canto-L's builder)",
                          "acorn (HNL)": "acorn (HNL) + MWS-layer + learned merging (Canto-L's builder)",
                          "acorn (ttbar+HNL)": "acorn (ttbar+HNL) + MWS-layer + learned merging (Canto-L's builder)"},
            "mwslayermerge": {"acorn (ttbar)": "acorn (ttbar) + MWS-layer + merging (Canto builder)",
                              "acorn (HNL)": "acorn (HNL) + MWS-layer + merging (Canto builder)",
                              "acorn (ttbar+HNL)": "acorn (ttbar+HNL) + MWS-layer + merging (Canto builder)"}}
PAIRED = os.path.join(RES, "training_sample_paired_v1.csv")
CANTO_NEW = {"mwslmerge": "Canto-L (frozen: learned merging)",
             "mwslayermerge": "Canto-L + MWS-layer + merging (Canto builder), same builder (not the frozen builder)"}


def sigmas(fam):
    d = pd.read_csv(os.path.join(RES, "strong_baselines_v3_val_differences.csv"))
    d = d[(d.set == "val") & (d.quantity == "primary")]
    out = {}
    for m, lab in SB_LABEL[fam].items():
        q = d[(d.baseline == lab) & (d.block == "Canto-L minus acorn")]
        out[m] = (float(q.value_base.iloc[0]), float(q.sigma_base.iloc[0]))
    q = d[(d.new == CANTO_NEW[fam])]
    out["Canto-L (ttbar)"] = (float(q.value_new.iloc[0]), float(q.sigma_new.iloc[0]))
    return out


def paired(fam, label, value=None):
    p = pd.read_csv(PAIRED)
    r = p[(p.family == fam) & (p.label == label)]
    assert len(r) == 1, (fam, label, len(r))
    r = r.iloc[0]
    if value is not None:
        assert abs(float(r.value) - value) < 1e-9, (fam, label, float(r.value), value)
    return r


def table(fam):
    t = pd.read_csv(os.path.join(RES, f"training_sample_val_{fam}.csv"))
    sig = sigmas(fam)
    spread = float(t[t.model == "Canto-L (ttbar)"].eff_primary.std(ddof=1))
    rows = {}
    for m in MODELS:
        g = t[t.model == m]
        if g.empty:
            continue
        p = float(g.eff_primary.mean())
        if m in sig:
            assert abs(sig[m][0] - p) < 1e-9, (fam, m, sig[m][0], p)
            s = sig[m][1]
        else:      # one seed: binomial error combined with the three-seed spread of Canto-L (ttbar), same builder
            s = float(np.hypot(np.sqrt(p * (1 - p) / g.eff_primary_n.iloc[0]), spread))
        rows[m] = {"n_seeds": len(g), "primary": p, "sigma": s, "ineff": 1 - p,
                   "d100": float(g.d0_100_300.mean()), "k300": int(g.d0_300_inf_k.sum()), "n300": int(g.d0_300_inf_n.sum()),
                   "w": float(g.eff_w_muons.mean()), "tt": float(g.eff_ttbar_prompt.mean()), "fake": float(g.fake_rate_hnl.mean()),
                   "wp": "; ".join(g.working_point)}
    return rows, spread


def pct(x, d=2):
    return f"{100 * x:.{d}f}"


def main():
    L = ["# Training-sample study: Canto-L and acorn trained on ttbar, on ttbar + HNL and on HNL (validation)", "",
         "Generated by scripts/diagnostics/training_sample_summary.py. Validation events only; Canto-L trained on HNL",
         "and on ttbar + HNL: one seed each (docs/training_sample_study.md); every other model: three seeds. Each model",
         "with the same builder family, its configuration chosen per seed on validation by the builder rule at FR*.", ""]
    for fam, name in (("mwslmerge", "MWS-layer + learned merging (LM)"), ("mwslayermerge", "MWS-layer + helix merging (MWS+M)")):
        rows, spread = table(fam)
        L += [f"## {name}", "", "| model | seeds | primary (%) | inefficiency (%) | 100-300 mm (%) | >= 300 mm | W muons (%) | "
              "ttbar prompt (%) | fake rate (%) |", "|---|---|---|---|---|---|---|---|---|"]
        for m, r in rows.items():
            L.append(f"| {m} | {r['n_seeds']} | {pct(r['primary'])} +- {pct(r['sigma'])} | {pct(r['ineff'])} | "
                     f"{pct(r['d100'], 1)} | {r['k300']}/{r['n300']} | {pct(r['w'], 1)} | {pct(r['tt'], 1)} | {pct(r['fake'])} |")
        L += ["", f"- {fam}: seed spread (sd) of Canto-L (ttbar) primary efficiency {pct(spread)} points"]
        for arch in ("acorn", "Canto-L"):
            a, b, c = rows.get(f"{arch} (ttbar)"), rows.get(f"{arch} (HNL)"), rows.get(f"{arch} (ttbar+HNL)")
            if a and b:
                lab = f"{arch}, trained on HNL minus trained on ttbar"
                r = paired(fam, lab, b["primary"] - a["primary"])
                L.append(f"- {fam}: {lab}: {100 * r.value:+.2f} +- {100 * r.sigma:.2f} points")
            if b and c:
                L.append(f"- {fam}: {arch}, trained on ttbar+HNL minus trained on HNL: {100 * (c['primary'] - b['primary']):+.2f} points")
        for samp in ("ttbar", "HNL", "ttbar+HNL"):
            a, c = rows.get(f"acorn ({samp})"), rows.get(f"Canto-L ({samp})")
            if a and c:
                L.append(f"- {fam}: trained on {samp}: inefficiency acorn {pct(a['ineff'])} %, Canto-L {pct(c['ineff'])} %, "
                         f"ratio acorn/Canto-L {a['ineff'] / c['ineff']:.1f}")
        L.append("")
    # edge efficiency at e*
    L += ["## Edge efficiency of HNL daughters at the common edge working point e* (seed 0 of each Canto-L)", ""]
    for samp, run in CANTO.items():
        e = pd.read_csv(os.path.join(run, "edge_tpr_estar.csv"))
        e = e[(e.population == "hnl_daughters") & (e.variable == "d0_bin")].set_index("bin")
        c = [x for x in e.columns if x.startswith("edge_eff@")][0]
        v = {b: float(e.loc[b, c]) for b in ("[100.0, 300.0)", "[300.0, inf)")}
        L.append(f"- e* edges, Canto-L ({samp}) s0, cut {c[9:]}: 100-300 mm {pct(v['[100.0, 300.0)'], 1)} %, "
                 f">= 300 mm {pct(v['[300.0, inf)'], 1)} % ({int(e.loc['[300.0, inf)', 'n_true_edges'])} edges)")
    # oblique classifier-stage losses
    ob = pd.concat([pd.read_csv(os.path.join(RES, f"oblique_val_{x}_v1_particles.csv")) for x in ("ref", "ii", "iii")])
    ob["fam"] = ob.label.str.replace(r" s\d$", "", regex=True)
    L += ["", "## Classifier-stage losses versus |d0| / r_first (graph ceiling matched; s0 = 0.2)", ""]
    for fam, name in (("Canto-L (i)", "Canto-L (ttbar), 3 seeds"), ("acorn (HNL)", "acorn (HNL), 3 seeds"),
                      ("Canto-L (ii)", "Canto-L (HNL), seed 0"), ("Canto-L (iii)", "Canto-L (ttbar+HNL), seed 0")):
        g = ob[(ob.fam == fam) & (ob.stage != "graph")]
        lo, hi = g[g.ratio < 0.7], g[g.ratio >= 0.7]
        L.append(f"- oblique, {name}: {100 * (lo.stage == 'classifier').mean():.1f} % below 0.7, "
                 f"{100 * (hi.stage == 'classifier').mean():.1f} % at >= 0.7 ({int((hi.stage == 'classifier').sum())} of {len(hi)})")
    for lab in ("Canto-L (i) s0", "Canto-L (ii) s0", "Canto-L (iii) s0"):
        g = ob[(ob.label == lab) & (ob.ratio >= 0.7)]
        L.append(f"- oblique seed 0, {lab}: classifier-stage losses at >= 0.7: {int((g.stage == 'classifier').sum())} of {len(g)}")
    L += ["", "## Checkpoint-selection events (HNL-trained runs chose checkpoints on 500 HNL validation events)", ""]
    for ln in open(os.path.join(RES, "diagnostics", "valmon_split.txt")):
        if ln.strip().startswith(("Canto-L", "acorn")) and len(ln.split()) >= 4 and "." in ln.split()[-1] and ln.split()[1] in ("(HNL)", "(ttbar)", "(ttbar+HNL)"):
            pass
    vm = pd.read_csv(os.path.join(RES, "diagnostics", "valmon_split.csv"))
    g = vm.groupby("model")[["valmon", "rest"]].mean() * 100
    for m in ("Canto-L (HNL)", "Canto-L (ttbar)", "acorn (HNL)", "acorn (ttbar)"):
        L.append(f"- valmon split, {m}: {g.loc[m, 'valmon']:.2f} % on the 500 events, {g.loc[m, 'rest']:.2f} % on the other 1499")
    L.append(f"- valmon split, on the other 1499 events trained on HNL minus trained on ttbar: acorn "
             f"{g.loc['acorn (HNL)', 'rest'] - g.loc['acorn (ttbar)', 'rest']:+.2f} points, Canto-L "
             f"{g.loc['Canto-L (HNL)', 'rest'] - g.loc['Canto-L (ttbar)', 'rest']:+.2f} points")
    L += ["", "## Differences with paired event-bootstrap uncertainties (results/training_sample_paired_v1.csv)", "",
          "Primary efficiency, points; sigma = sqrt(boot^2 + seeds^2), the seed term with the seed sd of Canto-L (ttbar)",
          "for each one-seed model; z = value / sigma; unpaired = the two models' sigmas in quadrature.", ""]
    for r in pd.read_csv(PAIRED).itertuples():
        un = f", unpaired {100 * r.sigma_unpaired:.2f}" if np.isfinite(r.sigma_unpaired) else ""
        L.append(f"- paired, {r.family}: {r.label}: {100 * r.value:+.2f} +- {100 * r.sigma:.2f} points "
                 f"(boot {100 * r.sigma_boot:.2f}, seeds {100 * r.sigma_seeds:.2f}{un}; z = {r.z:.1f})")
    out = os.path.join(RES, "training_sample_v1.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
